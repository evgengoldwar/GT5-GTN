    private void sanityCheck() {
        if (mHasNotBeenSet)
            throw new IllegalAccessError("The Enum '" + name() + "' has not been set to an Item at this time!");
        if (!mWarned) {
            GT_FML_LOGGER.error(new Exception(this + " is now deprecated"));
            // warn only once
            mWarned = true;
        }
    }
